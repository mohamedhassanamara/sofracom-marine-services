#!/usr/bin/env node
// Writes the status palette for the staff phone app (Flutter) from lib/design/tokens.js and
// the status labels from lib/i18n/en.js, so the app, the website and the admin use the same
// colours and words.
//
//   node scripts/export-staff-palette.mjs                    # print the Dart file
//   node scripts/export-staff-palette.mjs --write <app dir>  # write <app dir>/lib/status_palette.dart
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const { tones, statusTone } = require(path.join(ROOT, 'lib/design/tokens.js'));
const enSource = fs.readFileSync(path.join(ROOT, 'lib/i18n/en.js'), 'utf-8');
const en = new Function(`return (${enSource.slice(enSource.indexOf('{'), enSource.lastIndexOf('};') + 1)});`)();

const color = hex => `Color(0xFF${hex.replace('#', '').toUpperCase()})`;
const dartString = text => `'${String(text).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

export function staffPaletteDart() {
    const toneLines = Object.entries(tones)
        .map(([name, tone]) => `  '${name}': StatusTone(fg: ${color(tone.fg)}, bg: ${color(tone.bg)}, border: ${color(tone.border)}, solid: ${color(tone.solid)}),`)
        .join('\n');
    const statusLines = kind =>
        Object.entries(statusTone[kind])
            .map(([status, tone]) => `  StatusInfo(${dartString(status)}, ${dartString(en[`status.${kind}.${status}`])}, '${tone}'),`)
            .join('\n');
    return `// GENERATED by sofracom-marine-services/scripts/export-staff-palette.mjs from
// lib/design/tokens.js (tones + statusTone) and lib/i18n/en.js (status labels).
// Do not edit by hand: run \`node scripts/export-staff-palette.mjs --write <this app>\`.
import 'package:flutter/material.dart';

/// One status colour set: text on the tinted background passes WCAG AA; [solid] is for dots.
class StatusTone {
  const StatusTone({required this.fg, required this.bg, required this.border, required this.solid});

  final Color fg;
  final Color bg;
  final Color border;
  final Color solid;
}

const Map<String, StatusTone> statusTones = {
${toneLines}
};

class StatusInfo {
  const StatusInfo(this.value, this.label, this.toneName);

  final String value;
  final String label;
  final String toneName;

  StatusTone get tone => statusTones[toneName]!;
  Color get color => tone.solid;
}

const List<StatusInfo> orderStatuses = [
${statusLines('order')}
];

const List<StatusInfo> quoteStatuses = [
${statusLines('quote')}
];
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
    const writeIndex = process.argv.indexOf('--write');
    if (writeIndex > 0) {
        const target = path.join(path.resolve(process.argv[writeIndex + 1]), 'lib', 'status_palette.dart');
        fs.writeFileSync(target, staffPaletteDart());
        console.log(`wrote ${target}`);
    } else process.stdout.write(staffPaletteDart());
}
